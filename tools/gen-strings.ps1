# Generates src/strings.inc (UI text, UTF-16) and src/strings_status.inc
# (worker status text, UTF-8) from src/strings.json for every UI language.
# Works on Windows PowerShell 5.1 and PowerShell 7.
param([string]$ProjectRoot = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'
$languages = @('zh','en','ja')
$jsonPath = Join-Path (Join-Path $ProjectRoot 'src') 'strings.json'
$table = [IO.File]::ReadAllText($jsonPath,[Text.Encoding]::UTF8) | ConvertFrom-Json

function Get-Codepoints([string]$text) {
    $values = @($text.ToCharArray() | ForEach-Object { '0x{0:X4}' -f [int]$_ })
    $values += '0'
    return ($values -join ',')
}
function Get-Utf8Bytes([string]$text) {
    $values = @([Text.Encoding]::UTF8.GetBytes($text) | ForEach-Object { '0x{0:X2}' -f [int]$_ })
    $values += '0'
    return ($values -join ',')
}

# ---- UI strings: one packed UTF-16 table per language, copied into slots at runtime.
$ui = @($table.ui.PSObject.Properties)
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('; Generated by tools/gen-strings.ps1 from src/strings.json. Do not edit.')
$lines.Add(('LANG_COUNT = {0}' -f $languages.Count))
$lines.Add(('UI_STRING_COUNT = {0}' -f $ui.Count))
for ($l = 0; $l -lt $languages.Count; $l++) {
    $lines.Add(('uiLangData{0}:' -f $l))
    foreach ($property in $ui) {
        $lines.Add((' dw {0}' -f (Get-Codepoints $property.Value.($languages[$l]))))
    }
}
$lines.Add(('uiLangData dd {0}' -f ((0..($languages.Count - 1) | ForEach-Object { 'uiLangData' + $_ }) -join ',')))
$names = @($ui | ForEach-Object { $_.Name })
for ($i = 0; $i -lt $names.Count; $i += 12) {
    $last = [Math]::Min($i + 11,$names.Count - 1)
    $prefix = ' dd '
    if ($i -eq 0) { $prefix = 'uiStringSlots dd ' }
    $lines.Add($prefix + ($names[$i..$last] -join ','))
}
$lines.Add('; Slots are reserved storage sized for the longest translation.')
foreach ($property in $ui) {
    $capacity = 0
    foreach ($language in $languages) {
        $length = $property.Value.$language.Length
        if ($length -gt $capacity) { $capacity = $length }
    }
    $lines.Add(('{0} rw {1}' -f $property.Name,($capacity + 1)))
}
[IO.File]::WriteAllLines((Join-Path (Join-Path $ProjectRoot 'src') 'strings.inc'),$lines,[Text.Encoding]::ASCII)

# ---- Worker status text: pointer map (source label -> per-language text).
$status = @($table.status.PSObject.Properties)
$out = New-Object System.Collections.Generic.List[string]
$out.Add('; Generated by tools/gen-strings.ps1 from src/strings.json. Do not edit.')
$out.Add(('STATUS_STRING_COUNT = {0}' -f $status.Count))
$data = New-Object System.Collections.Generic.List[string]
$index = 0
foreach ($property in $status) {
    $pointers = @($property.Name)
    foreach ($language in $languages) {
        if ($property.Value.source -eq $language) {
            $pointers += $property.Name
        } else {
            $label = 'statusText{0}_{1}' -f $index,$language
            $pointers += $label
            $data.Add(('{0} db {1}' -f $label,(Get-Utf8Bytes $property.Value.$language)))
        }
    }
    $prefix = ' dd '
    if ($index -eq 0) { $prefix = 'statusMap dd ' }
    $out.Add($prefix + ($pointers -join ','))
    $index++
}
foreach ($line in $data) { $out.Add($line) }
[IO.File]::WriteAllLines((Join-Path (Join-Path $ProjectRoot 'src') 'strings_status.inc'),$out,[Text.Encoding]::ASCII)
